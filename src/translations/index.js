export const TRANSLATIONS = {
  en: flatEn,
  kn: flatKn,
  hi: flatHi,
};

/**
 * Enhanced Translator Function (Resolves by key, nested key, or English string fallback)
 * @param {string} lang - 'en' | 'kn' | 'hi'
 * @param {string} keyOrText - Key or user-visible English text
 * @param {string} [fallback] - Optional fallback text
 * @param {Object} [params] - Optional interpolation parameters (e.g. { count: 5 })
 */
export const translate = (lang = 'en', keyOrText = '', fallback = '', params = null) => {
  if (!keyOrText && !fallback) return '';
  const currentLang = ['en', 'kn', 'hi'].includes(lang) ? lang : 'en';
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;

  let resolved = null;

  // 1. Direct dictionary match
  if (keyOrText && dict[keyOrText]) {
    resolved = dict[keyOrText];
  }

  // 2. Lookup by lowercase/trimmed string in English map
  if (!resolved && typeof keyOrText === 'string') {
    const normalized = keyOrText.trim().toLowerCase();
    const mappedKey = ENGLISH_TO_KEY[normalized];
    if (mappedKey && dict[mappedKey]) {
      resolved = dict[mappedKey];
    }
  }

  // 3. Fallback resolution if provided and different
  if (!resolved && fallback && typeof fallback === 'string') {
    if (dict[fallback]) {
      resolved = dict[fallback];
    } else {
      const normalizedFb = fallback.trim().toLowerCase();
      const mappedFbKey = ENGLISH_TO_KEY[normalizedFb];
      if (mappedFbKey && dict[mappedFbKey]) {
        resolved = dict[mappedFbKey];
      }
    }
  }

  // 4. Default to English translation or raw string
  if (!resolved) {
    if (TRANSLATIONS.en[keyOrText]) {
      resolved = TRANSLATIONS.en[keyOrText];
    } else {
      resolved = fallback || keyOrText;
    }
  }

  // 5. Interpolate params if provided (e.g. {count}, {name})
  if (params && typeof resolved === 'string') {
    for (const [k, v] of Object.entries(params)) {
      resolved = resolved.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }

  return resolved;
};

