// Helper to flatten nested domain dictionaries into a single lookup map
const flattenDomain = (obj, prefix = '') => {
  const result = {};
  for (const [key, val] of Object.entries(obj)) {
    if (typeof val === 'object' && val !== null && !Array.isArray(val)) {
      const nested = flattenDomain(val, `${prefix}${key}.`);
      Object.assign(result, nested);
      // Also register bare key if not collision
      for (const [subK, subV] of Object.entries(val)) {
        if (!result[subK]) {
          result[subK] = subV;
        }
      }
    } else {
      result[`${prefix}${key}`] = val;
    }
  }
  return result;
};

